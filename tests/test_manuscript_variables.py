"""Tests for skyfall.manuscript_variables — {{TOKEN}} hydration + figure.

Real config + domain computation only (zero mocks). Includes the live
cross-reference gate: every {{TOKEN}} in numbered manuscript sections must be
generated by generate_variables().
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import pytest

PACKAGE_ROOT = Path(__file__).resolve().parent.parent
_FAKE_CONFIG_OK = """\
paper:
  title: "Skyfall: SILVA"
  subtitle: "Mission Software"
  version: "0.1.0"
  film: "skyfall"
mission:
  codename: "SILVA"
"""

_FAKE_CONFIG_BAD = """\
paper: []
"""


def _write(tmp_path: Path, body: str, name: str = "config.yaml") -> Path:
    path = tmp_path / name
    path.write_text(body, encoding="utf-8")
    return path


