"""Tests for skyfall.manuscript_variables — {{TOKEN}} hydration + figure.

Real config + domain computation only (zero mocks). Includes the live
cross-reference gate: every {{TOKEN}} in numbered manuscript sections must be
generated by generate_variables().
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import pytest

PACKAGE_ROOT = Path(__file__).resolve().parent.parent
_FAKE_CONFIG_OK = """\
paper:
  title: "Skyfall: SILVA"
  subtitle: "Mission Software"
  version: "0.1.0"
  film: "skyfall"
mission:
  codename: "SILVA"
"""

_FAKE_CONFIG_BAD = """\
paper: []
"""


def _write(tmp_path: Path, body: str, name: str = "config.yaml") -> Path:
    path = tmp_path / name
    path.write_text(body, encoding="utf-8")
    return path


class TestLoadConfig:
    def test_missing_file(self, tmp_path: Path) -> None:
        from skyfall.manuscript_variables import load_manuscript_config

        with pytest.raises(FileNotFoundError):
            load_manuscript_config(tmp_path / "missing.yaml")

    def test_non_mapping(self, tmp_path: Path) -> None:
        from skyfall.manuscript_variables import load_manuscript_config

        cfg = _write(tmp_path, "just a string")
        with pytest.raises(ValueError):
            load_manuscript_config(cfg)


class TestGenerateVariables:
    def test_default_config(self) -> None:
        from skyfall.manuscript_variables import generate_variables

        vars_ = generate_variables()
        assert vars_["SILVA_CODENAME"] == "SILVA"
        assert vars_["SILVA_FLEET_SIZE"] == "5"
        assert vars_["SILVA_COVERAGE"] == "1.00"
        assert vars_["SILVA_SHORTEST_HOPS"] == "5"

    def test_explicit_config_path(self, tmp_path: Path) -> None:
        from skyfall.manuscript_variables import generate_variables

        cfg = _write(tmp_path, _FAKE_CONFIG_OK)
        vars_ = generate_variables(config_path=cfg)
        assert vars_["SILVA_TITLE"] == "Skyfall: SILVA"

    def test_bad_paper_section(self, tmp_path: Path) -> None:
        from skyfall.manuscript_variables import generate_variables

        cfg = _write(tmp_path, _FAKE_CONFIG_BAD)
        with pytest.raises(ValueError):
            generate_variables(config_path=cfg)

    def test_deterministic_metrics(self) -> None:
        from skyfall.manuscript_variables import generate_variables

        a = generate_variables()
        b = generate_variables()
        for key in ("SILVA_SHORTEST_HOPS", "SILVA_MEAN_EXPOSURE", "SILVA_COVERAGE"):
            assert a[key] == b[key]


class TestResolveTree:
    def test_resolve_writes_outputs(self, tmp_path: Path) -> None:
        from skyfall.manuscript_variables import generate_variables, resolve_manuscript_tree

        manu_dir = tmp_path / "manuscript"
        manu_dir.mkdir()
        (manu_dir / "00_abstract.md").write_text("Film: {{SILVA_FILM}} codename {{SILVA_CODENAME}}", encoding="utf-8")
        (manu_dir / "SYNTAX.md").write_text("guide with {{LITERAL}} kept", encoding="utf-8")  # sidecar not copied
        out_dir = tmp_path / "out"
        variables = generate_variables(config_path=_write(tmp_path, _FAKE_CONFIG_OK))
        result_dir, names = resolve_manuscript_tree(variables, manuscript_dir=manu_dir, output_dir=out_dir)
        assert names == ["00_abstract.md"]
        text = (out_dir / "00_abstract.md").read_text(encoding="utf-8")
        assert "skyfall" in text and "SILVA" in text
        assert "{{" not in text

    def test_strict_fails_on_unresolved(self, tmp_path: Path) -> None:
        from skyfall.manuscript_variables import generate_variables, resolve_manuscript_tree

        manu_dir = tmp_path / "manuscript"
        manu_dir.mkdir()
        (manu_dir / "01_intro.md").write_text("leftover {{UNKNOWN_TOKEN}}", encoding="utf-8")
        variables = generate_variables(config_path=_write(tmp_path, _FAKE_CONFIG_OK))
        with pytest.raises(ValueError):
            resolve_manuscript_tree(variables, manuscript_dir=manu_dir, output_dir=tmp_path / "out")


def test_live_manuscript_token_cross_reference() -> None:
    """Every {{TOKEN}} in numbered manuscript sections must be generated."""
    from skyfall.manuscript_variables import generate_variables

    variables = generate_variables()
    token_re = re.compile(r"\{\{([A-Z0-9_]+)\}\}")
    manuscript_dir = PACKAGE_ROOT / "manuscript"
    used: set[str] = set()
    for section in sorted(manuscript_dir.glob("[0-9][0-9]_*.md")):
        used.update(token_re.findall(section.read_text(encoding="utf-8")))
    missing = sorted(t for t in used if t not in variables)
    assert not missing, f"manuscript tokens not generated: {missing}"


def test_manuscript_variables_json_smoke(tmp_path: Path):
    """The generate-script's JSON output shape is stable and key-sorted."""
    from skyfall.manuscript_variables import generate_variables

    vars_ = generate_variables()
    payload = json.dumps(vars_, sort_keys=True, indent=2)
    assert json.loads(payload) == vars_
    assert (tmp_path / "x.json").write_text(payload, encoding="utf-8") > 0
