    def test_missing_file(self, tmp_path: Path) -> None:
        from skyfall.manuscript_variables import load_manuscript_config

        with pytest.raises(FileNotFoundError):
            load_manuscript_config(tmp_path / "missing.yaml")

    def test_non_mapping(self, tmp_path: Path) -> None:
        from skyfall.manuscript_variables import load_manuscript_config

        cfg = _write(tmp_path, "just a string")
        with pytest.raises(ValueError):
            load_manuscript_config(cfg)


